"""Create deterministic, metadata-first training observation sidecars.

The base labels/sources remain immutable. Observation images are generated by
the future trainer from these records, so this step does not duplicate 5,000
large arrays or introduce real pixels. The manifest is the frozen population
contract for probe arms.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "data/package"
SELECTION = ROOT / "config/selected_scene_ids.json"
OUT = ROOT / "data/training_observations"


def sha(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def build(scope: str, force: bool = False) -> dict:
    if scope not in {"short", "full"}: raise ValueError(scope)
    OUT.mkdir(parents=True, exist_ok=True)
    output = OUT / f"{scope}_manifest.json"
    if output.exists() and not force: raise FileExistsError(output)
    base = json.loads((PACKAGE / "manifest.json").read_text(encoding="utf-8-sig"))
    by_id = {int(r["scene_index"]): r for r in base["records"] if r["split"] == "train"}
    selection = json.loads(SELECTION.read_text(encoding="utf-8-sig"))
    key = "short_sequence_enrichment_ids" if scope == "short" else "full_sequence_enrichment_ids"
    expected = 96 if scope == "short" else 960
    ids = [int(value) for value in selection[key]]
    if len(ids) != expected or len(set(ids)) != expected: raise ValueError(f"{key} is not frozen at {expected} unique IDs")
    if any(value not in by_id for value in ids): raise ValueError("selected ID is not a train record")
    if any(by_id[value]["role"] == "flat_negative" for value in ids): raise ValueError("flat_negative cannot be a sequence enrichment geometry")
    groups = {}
    for value in ids:
        record = by_id[value]; groups.setdefault((record["family"], int(record["polarity"])), []).append(value)
    if len(groups) != 24 or any(len(v) != expected // 24 for v in groups.values()): raise ValueError("family/polarity strata are not balanced")
    rows = []
    for order, scene_id in enumerate(ids):
        record = by_id[scene_id]
        rows.append({"scene_id": scene_id, "family": record["family"], "polarity": record["polarity"], "role": record["role"], "target_a": record["target_a"], "target_b": record["target_b"], "source_a": record["source_a"], "source_b": record["source_b"], "sdf_a": record["sdf_a"], "sdf_b": record["sdf_b"], "mask_a": record["mask_a"], "mask_b": record["mask_b"], "pair_dx_px": record["pair_dx_px"], "pair_dy_px": record["pair_dy_px"], "observation_schedule": {"static_repeat": 2, "motion_x": 2, "motion_y": 2, "motion_diag": 2, "exposure_static": 2, "blur_static": 2}, "fixed_optics_motion": True, "same_latent_pair": True, "label_supersample_factor": 8, "observation_seed": 1196001 + order * 1009, "source_record_seed": record["seed"], "new_asymmetric_conditions": scope == "full"})
    result = {"schema_version": 1, "status": "complete", "created_at_utc": datetime.now(timezone.utc).isoformat(), "scope": scope, "base_manifest_sha256": sha(PACKAGE / "manifest.json"), "selection_sha256": sha(SELECTION), "scene_count": len(rows), "expected_scene_count": expected, "population": "train only; metadata-first deterministic observations; no real SEM/Raw pixels", "records": rows, "conditions": {"motion": {"positions_px": [-1, -.875, -.75, -.625, -.5, -.375, -.25, -.125, 0, .125, .25, .375, .5, .625, .75, .875, 1]}, "exposure_gain": [.7, .85, 1, 1.15, 1.3], "asymmetric_kernel": {"tail_mix": .23, "tail_offset_px": [3, -.4], "tail_sigma_px": [2.8, 1.3], "kernel_centroid_locked": True}}, "generation": "trainer-side 8x replay then optical/sensor observation; no translated downsampled labels"}
    output.write_text(json.dumps(result, indent=2), encoding="utf-8")
    return result


def main():
    parser = argparse.ArgumentParser(); parser.add_argument("--scope", choices=["short", "full"], required=True); parser.add_argument("--force", action="store_true")
    args = parser.parse_args(); result = build(args.scope, args.force); print(json.dumps({k: result[k] for k in ("status", "scope", "scene_count", "expected_scene_count", "base_manifest_sha256", "selection_sha256")}, indent=2)); return 0


if __name__ == "__main__": raise SystemExit(main())
