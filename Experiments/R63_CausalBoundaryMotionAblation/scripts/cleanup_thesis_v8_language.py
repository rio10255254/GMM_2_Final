def has_protected_content(paragraph) -> bool:
    """Return True when rebuilding the paragraph could remove a field, equation, or image."""
    p = paragraph._p
    return bool(
        p.xpath(".//m:oMath")
        or p.xpath(".//m:oMathPara")
        or p.xpath(".//w:fldChar")
        or p.xpath(".//w:instrText")
        or p.xpath(".//w:drawing")
        or p.xpath(".//w:pict")
        or p.xpath(".//w:object")
    )


def replace_paragraph_text(paragraph, text: str) -> None:
    if has_protected_content(paragraph):
        raise RuntimeError(f"Protected paragraph cannot be rebuilt: {paragraph.text[:80]!r}")

    first_rpr = None
    for run in paragraph.runs:
        if run._r.rPr is not None:
            first_rpr = deepcopy(run._r.rPr)
            break

    p = paragraph._p
    for child in list(p):
        if child.tag != qn("w:pPr"):
            p.remove(child)

    run = paragraph.add_run(text)
    if first_rpr is not None:
        if run._r.rPr is not None:
            run._r.remove(run._r.rPr)
        run._r.insert(0, first_rpr)


def replace_at(document: Document, index: int, expected_prefix: str, text: str) -> None:
    paragraph = document.paragraphs[index]
    actual = paragraph.text.strip()
    if not actual.startswith(expected_prefix):
        raise RuntimeError(
            f"Paragraph {index} mismatch: expected {expected_prefix!r}, got {actual[:100]!r}"
        )
    if has_protected_content(paragraph):
        print(f"SKIP_PROTECTED:{index}:{actual[:80]}")
        return
    replace_paragraph_text(paragraph, text)


def all_non_field_paragraphs(document: Document):
    for paragraph in document.paragraphs:
        yield paragraph
    for table in document.tables:
        for row in table.rows:
            for cell in row.cells:
                for paragraph in cell.paragraphs:
                    yield paragraph
    for section in document.sections:
        for container in (section.header, section.footer):
            for paragraph in container.paragraphs:
                yield paragraph
            for table in container.tables:
                for row in table.rows:
                    for cell in row.cells:
                        for paragraph in cell.paragraphs:
                            yield paragraph


def replace_visible_terms(document: Document, replacements: list[tuple[str, str]]) -> None:
    for paragraph in all_non_field_paragraphs(document):
        if not paragraph.text or has_protected_content(paragraph):
            continue
        updated = paragraph.text
        for old, new in replacements:
            updated = updated.replace(old, new)
        if updated != paragraph.text:
            replace_paragraph_text(paragraph, updated)


def replace_table_cell(document: Document, table_index: int, row: int, column: int, text: str) -> None:
    cell = document.tables[table_index].cell(row, column)
    if len(cell.paragraphs) != 1:
        raise RuntimeError(f"Unexpected paragraph count in table {table_index}, cell {row},{column}")
    replace_paragraph_text(cell.paragraphs[0], text)


