"""Freeze the tested R92 implementation before formal data generation."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from datetime import datetime
from pathlib import Path
import subprocess


ROOT = Path(__file__).resolve().parents[1]
LOCK_PATH = ROOT / "config" / "implementation_lock.json"
FILES = (
    "model/r92_model.py",
    "training/train_r92.py",
    "inference/reconstruct.py",
    "scripts/generate_dataset.py",
    "scripts/launch_r92.py",
    "scripts/benchmark_r92.py",
    "scripts/repair_unprojectable_observations.py",
    "scripts/repair_recoverability.py",
    "scripts/repair_exposure_span.py",
    "config/experiment_design.json",
    "config/acceptance_gates.json",
    "config/execution_authorization.json",
    "config/optical_statistics.json",
    "config/gpu_safety_profile.json",
)


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(8 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--replace-before-formal", action="store_true")
    args = parser.parse_args()
    registry_path = ROOT / "runs" / "formal_run_registry.json"
    if registry_path.is_file() and json.loads(registry_path.read_text(encoding="utf-8")).get("formal_runs"):
        raise RuntimeError("Implementation cannot be re-frozen after a formal run is registered")
    if LOCK_PATH.exists() and not args.replace_before_formal:
        raise FileExistsError("Implementation lock already exists")
    benchmark_path = ROOT / "results" / "setup_benchmark.json"
    smoke_audit_path = ROOT / "data" / "r92_smoke" / "audit.json"
    smoke_manifest_path = ROOT / "data" / "r92_smoke" / "manifest.json"
    if not all(path.is_file() for path in (benchmark_path, smoke_audit_path, smoke_manifest_path)):
        raise FileNotFoundError("Benchmark and audited smoke data are required before freezing")
    benchmark = json.loads(benchmark_path.read_text(encoding="utf-8"))
    smoke_audit = json.loads(smoke_audit_path.read_text(encoding="utf-8"))
    smoke_manifest = json.loads(smoke_manifest_path.read_text(encoding="utf-8"))
    hashes = {relative: sha256_file(ROOT / relative) for relative in FILES}
    expected_benchmark = {
        "architecture_sha256": hashes["model/r92_model.py"],
        "trainer_sha256": hashes["training/train_r92.py"],
        "inference_sha256": hashes["inference/reconstruct.py"],
    }
    if any(benchmark.get(key) != value for key, value in expected_benchmark.items()):
        raise RuntimeError("Setup benchmark is stale")
    if benchmark.get("benchmark_scope") != "setup_cpu" or not benchmark.get("stages"):
        raise RuntimeError("A completed CPU setup benchmark is required before freezing")
    if not smoke_audit.get("passed") or not smoke_audit.get("full_array_hash_audit"):
        raise RuntimeError("Smoke data audit is not complete")
    if smoke_manifest.get("generator_sha256") != hashes["scripts/generate_dataset.py"]:
        raise RuntimeError("Smoke data were generated by a different generator")
    branch = subprocess.run(["git", "branch", "--show-current"], cwd=ROOT, check=True, capture_output=True, text=True).stdout.strip()
    payload = {
        "schema_version": 1,
        "experiment_id": "R92_PhysicalTransitionBalancedScratch",
        "status": "frozen_before_formal_data",
        "frozen_at": datetime.now().isoformat(),
        "branch": branch,
        "files": hashes,
        "setup_benchmark_sha256": sha256_file(benchmark_path),
        "smoke_dataset_content_sha256": smoke_manifest["content_sha256"],
        "smoke_audit_sha256": sha256_file(smoke_audit_path),
        "formal_run_registry_empty": True,
    }
    temporary = LOCK_PATH.with_suffix(".json.tmp")
    temporary.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    os.replace(temporary, LOCK_PATH)
    print(json.dumps(payload, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
