function run_wide_patch_probe(split_name)
%RUN_WIDE_PATCH_PROBE Test whether observing more of each PSF tail helps.
split_name = char(split_name);
here = fileparts(mfilename('fullpath'));
run_root = fileparts(here);
psf_root = fileparts(fileparts(run_root));
addpath(psf_root);
addpath(fullfile(psf_root, 'PSF_Fitting_ValidationLab', 'scripts'));
addpath(fullfile(psf_root, 'SimulatePSF'));
addpath(genpath(fullfile(psf_root, 'bads-1.1.3')));
if strcmp(split_name, 'A')
    frames = [1 13 25];
elseif strcmp(split_name, 'B')
    frames = [4 7 12 18 23];
else
    error('Unknown split name.');
end
input_root = fullfile(here, 'wide_input');
output_root = fullfile(here, ['wide_profile_gain_' split_name]);
rng(20260924, 'twister');
result = HDR_fitting_2D_WholeFOV_reasonable_v1( ...
    'subset_indices', frames, ...
    'input_folder', input_root, ...
    'gt_path', fullfile(input_root, 'GT', 'gt_sem_cd.bmp'), ...
    'loss_mask_path', fullfile(input_root, ['loss_mask_train6_' split_name '.bmp']), ...
    'grid_rows', 5, 'grid_cols', 5, ...
    'image_pattern', 'fit_input_*.bmp', ...
    'warm_start', false, ...
    'pre_alignment', false, ...
    'lock_tilt', true, ...
    'psf_scale', 0.125 / (3.45 / 20), ...
    'aberration_bound_scale', 2, ...
    'gradient_weight', 0.1, ...
    'fix_locked_tilt_in_bads', true, ...
    'fix_amplitude_in_bads', true, ...
    'profile_gain', true, ...
    'bads_options', struct('Display', 'off', 'UncertaintyHandling', false), ...
    'output_root', output_root, ...
    'use_gpu', false);
assert(result.num_images == numel(frames));
fprintf('Wide crop split %s complete.\n', split_name);
end
