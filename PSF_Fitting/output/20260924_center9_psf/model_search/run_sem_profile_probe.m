function run_sem_profile_probe(fold_name, gradient_weight)
%RUN_SEM_PROFILE_PROBE Fit actual SEM outline with separately profiled gain.
fold_name = char(fold_name);
root = fileparts(mfilename('fullpath'));
run_root = fileparts(root);
psf_root = fileparts(fileparts(run_root));
addpath(psf_root);
addpath(fullfile(psf_root, 'PSF_Fitting_ValidationLab', 'scripts'));
addpath(fullfile(psf_root, 'SimulatePSF'));
addpath(genpath(fullfile(psf_root, 'bads-1.1.3')));
if strcmp(fold_name, 'A')
    frames = [1 13 25];
    mask_path = fullfile(run_root, 'fit_input', 'loss_mask_train6.bmp');
elseif strcmp(fold_name, 'B')
    frames = [4 7 12 18 23];
    mask_path = fullfile(run_root, 'fit_input', 'loss_mask_train6_B.bmp');
elseif strcmp(fold_name, 'C')
    frames = [3 8 14 20 22];
    mask_path = fullfile(root, 'loss_mask_train6_C.bmp');
else
    error('Unknown fold.');
end
input_root = fullfile(run_root, 'fit_input');
gt_path = fullfile(run_root, 'sem_shape_forward_validation', 'gt_sem_contour_20x.bmp');
assert(isfile(gt_path));
tag = strrep(sprintf('%.3g', gradient_weight), '.', 'p');
output_root = fullfile(root, ['sem_profile_' tag '_' fold_name]);
rng(20260924, 'twister');
result = HDR_fitting_2D_WholeFOV_reasonable_v1( ...
    'subset_indices', frames, ...
    'input_folder', input_root, ...
    'gt_path', gt_path, ...
    'loss_mask_path', mask_path, ...
    'grid_rows', 5, 'grid_cols', 5, ...
    'image_pattern', 'fit_input_*.bmp', ...
    'warm_start', false, ...
    'pre_alignment', false, ...
    'lock_tilt', true, ...
    'psf_scale', 0.125 / (3.45 / 20), ...
    'aberration_bound_scale', 2, ...
    'gradient_weight', gradient_weight, ...
    'fix_locked_tilt_in_bads', true, ...
    'fix_amplitude_in_bads', true, ...
    'profile_gain', true, ...
    'bads_options', struct('Display', 'off', 'UncertaintyHandling', false), ...
    'output_root', output_root, ...
    'use_gpu', false);
assert(result.num_images == numel(frames));
fprintf('SEM profile fit fold %s, weight %g completed.\n', fold_name, gradient_weight);
end
