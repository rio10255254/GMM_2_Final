function run_reference_full_E()
%RUN_REFERENCE_FULL_E Fair original and prior research BADS references on E.
root = fileparts(mfilename('fullpath'));
run_root = fileparts(root);
psf_root = fileparts(fileparts(run_root));
addpath(psf_root);
addpath(fullfile(psf_root, 'PSF_Fitting_ValidationLab', 'scripts'));
addpath(fullfile(psf_root, 'SimulatePSF'));
addpath(genpath(fullfile(psf_root, 'bads-1.1.3')));
input_root = fullfile(run_root, 'parameter_audit', 'wide_input');
gt_path = fullfile(input_root, 'GT', 'gt_sem_cd.bmp');
mask_path = fullfile(root, 'full_train6_E.bmp');
frames = [5 9 11 16 19 21];

rng(20260924, 'twister');
original = HDR_fitting_2D_WholeFOV_reasonable_v1( ...
    'subset_indices', frames, 'input_folder', input_root, 'gt_path', gt_path, ...
    'loss_mask_path', mask_path, 'grid_rows', 5, 'grid_cols', 5, ...
    'image_pattern', 'fit_input_*.bmp', 'warm_start', false, ...
    'pre_alignment', false, 'lock_tilt', true, ...
    'psf_scale', 0.125 / (3.45 / 20), 'aberration_bound_scale', 2, ...
    'output_root', fullfile(root, 'original_full_E'), 'use_gpu', false);
assert(original.num_images == 6);

rng(20260924, 'twister');
profiled = HDR_fitting_2D_WholeFOV_reasonable_v1( ...
    'subset_indices', frames, 'input_folder', input_root, 'gt_path', gt_path, ...
    'loss_mask_path', mask_path, 'grid_rows', 5, 'grid_cols', 5, ...
    'image_pattern', 'fit_input_*.bmp', 'warm_start', false, ...
    'pre_alignment', false, 'lock_tilt', true, ...
    'psf_scale', 0.125 / (3.45 / 20), 'aberration_bound_scale', 2, ...
    'gradient_weight', 0.1, 'fix_locked_tilt_in_bads', true, ...
    'fix_amplitude_in_bads', true, 'profile_gain', true, ...
    'bads_options', struct('Display', 'off', 'UncertaintyHandling', false), ...
    'output_root', fullfile(root, 'profile_full_E'), 'use_gpu', false);
assert(profiled.num_images == 6);
fprintf('Two BADS reference fits complete for frozen fold E.\n');
end
