function run_sem_contour_cv()
%RUN_SEM_CONTOUR_CV Fit existing BADS model using actual SEM pillar outlines.
validation_root = fileparts(mfilename('fullpath'));
run_root = fileparts(validation_root);
psf_root = fileparts(fileparts(run_root));
addpath(psf_root);
addpath(fullfile(psf_root, 'PSF_Fitting_ValidationLab', 'scripts'));
addpath(fullfile(psf_root, 'SimulatePSF'));
addpath(genpath(fullfile(psf_root, 'bads-1.1.3')));
input_root = fullfile(run_root, 'fit_input');
gt_path = fullfile(validation_root, 'gt_sem_contour_20x.bmp');
assert(isfile(gt_path), 'Actual SEM-contour target is missing.');
for scale = [1 2 4 8]
    output_root = fullfile(validation_root, sprintf('cv_sem_bounds_%d', scale));
    fprintf('SEM-contour BADS fit, bound scale %d, frames 1/13/25.\n', scale);
    result = HDR_fitting_2D_WholeFOV_reasonable_v1( ...
        'subset_indices', [1 13 25], ...
        'input_folder', input_root, ...
        'gt_path', gt_path, ...
        'loss_mask_path', fullfile(input_root, 'loss_mask_train6.bmp'), ...
        'grid_rows', 5, 'grid_cols', 5, ...
        'image_pattern', 'fit_input_*.bmp', ...
        'warm_start', false, ...
        'pre_alignment', false, ...
        'lock_tilt', true, ...
        'psf_scale', 0.125 / (3.45 / 20), ...
        'aberration_bound_scale', scale, ...
        'output_root', output_root, ...
        'use_gpu', false);
    assert(result.num_images == 3, 'Incomplete SEM contour CV fit.');
end
end
