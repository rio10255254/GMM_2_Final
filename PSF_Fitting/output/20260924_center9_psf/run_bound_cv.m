function run_bound_cv()
%RUN_BOUND_CV Fit six pillars; reserve three for bound-range selection.
root = fileparts(mfilename('fullpath'));
psf_root = fileparts(fileparts(root));
addpath(psf_root);
addpath(fullfile(psf_root, 'PSF_Fitting_ValidationLab', 'scripts'));
addpath(fullfile(psf_root, 'SimulatePSF'));
addpath(genpath(fullfile(psf_root, 'bads-1.1.3')));
input_root = fullfile(root, 'fit_input');
for scale = [1 2 4 8]
    output_root = fullfile(root, sprintf('cv_bounds_%d', scale));
    fprintf('Bound scale %d: fitting frames 1, 13, 25 with three pillars held out.\n', scale);
    result = HDR_fitting_2D_WholeFOV_reasonable_v1( ...
        'subset_indices', [1 13 25], ...
        'input_folder', input_root, ...
        'gt_path', fullfile(input_root, 'GT', 'gt_sem_cd.bmp'), ...
        'loss_mask_path', fullfile(input_root, 'loss_mask_train6.bmp'), ...
        'grid_rows', 5, 'grid_cols', 5, ...
        'image_pattern', 'fit_input_*.bmp', ...
        'warm_start', false, ...
        'pre_alignment', false, ...
        'lock_tilt', true, ...
        'psf_scale', 0.125 / (3.45 / 20), ...
        'aberration_bound_scale', scale, ...
        'output_root', output_root, ...
        'use_gpu', false);
    assert(result.num_images == 3, 'Incomplete bound CV fit.');
end
end
