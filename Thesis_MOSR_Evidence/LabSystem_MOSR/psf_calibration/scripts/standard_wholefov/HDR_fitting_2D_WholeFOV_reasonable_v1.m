end

function write_json(output_path, payload)
json_text = jsonencode(payload, PrettyPrint = true);
fid = fopen(output_path, 'w');
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '%s\n', json_text);
end
