"""Publish the verified R61 training-data generator ZIP and check its contents."""
from __future__ import annotations

from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
from pathlib import Path
import zipfile

PROJECT = Path(__file__).resolve().parents[1]
PACKAGE = PROJECT / "Deliverables/Data_Regenerators/R61_TrainingData_Regenerator_20261004"
VALIDATION = PROJECT / "Deliverables/Validations/R61_TrainingData_Regenerator_20261004"
ZIP = PACKAGE.with_suffix(".zip")


def sha256(path: Path) -> str:
    result = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            result.update(chunk)
    return result.hexdigest()


def main() -> None:
    full = json.loads((VALIDATION / "full_rebuild_check.json").read_text(encoding="utf-8"))
    portable = json.loads((VALIDATION / "portability_check.json").read_text(encoding="utf-8"))
    controls = json.loads((VALIDATION / "input_and_output_guards.json").read_text(encoding="utf-8"))
    if any(item["status"] != "pass" for item in (full, portable, controls)):
        raise RuntimeError("The rebuild or portability checks have not passed")
    if full["identical_training_files"] != 114283 or full["total_pairs"] != 20296:
        raise RuntimeError("The full original training dataset has not been reproduced")
    requested = json.loads((PROJECT / "Deliverables/Company_Packages/MOSR_R61_ONNX/manifest.json").read_text(encoding="utf-8"))
    weight = PROJECT / "LabSystem_MOSR/Traing_Progress/training_progress_LAB_GESR_v1_v5_ST0p8_SWP_r61_motion_texture_stepguard_v16_dualgate_boundary_focus_full_e8_20260623_20260623_200020/weights/best_tradeoff.pth.tar"
    model_match = sha256(weight) == requested["source_checkpoint_sha256"]
    if not model_match:
        raise RuntimeError("The R61 dataset lineage does not match the requested ONNX model")
    verification = {
        "status": "pass",
        "tested_date": "2026-10-04",
        "requested_R61_ONNX_source_checkpoint_matches_v16": model_match,
        "source_checkpoint_sha256": requested["source_checkpoint_sha256"],
        "full_rebuild": full,
        "portable_rebuild": portable,
        "input_and_output_guards": controls,
        "original_program_with_recomputed_inherited_geometry": json.loads((PACKAGE / "reference/original_generator_rebuild_check.json").read_text(encoding="utf-8")),
        "faithful_rebuild_policy": "All 3400 inherited image/label/annotation sets are frozen original inputs; all 16896 synthetic image/label/annotation sets are generated by the unchanged original program",
    }
    (PACKAGE / "VERIFICATION.json").write_text(json.dumps(verification, indent=2, ensure_ascii=False), encoding="utf-8")
    readme = PACKAGE / "README_TW.md"
    text = readme.read_text(encoding="utf-8")
    text += "\n## 2026-10-04 交付前實測\n\n已在新建的 Python 3.12 環境，把資料包放到另一個位置，並阻擋讀取原專案的 LabSystem_MOSR 資料。完整生成 20,296 組後，114,283 份影像、答案、輪廓標記、移動記錄和分組檔案逐份相同；資料描述除生成日期、來源位置外也全部相同。訓練 18,266 組、驗證 2,030 組，分組與原版相同。缺少來源與既有輸出兩種情況，也確認會停止並保留既有內容。\n"
    readme.write_text(text, encoding="utf-8")
    files = sorted(path for path in PACKAGE.rglob("*") if path.is_file() and path.name != "PACKAGE_FILES.jsonl")
    for path in files:
        if "__pycache__" in path.parts or ".venv" in path.parts or "generated_training_data" in path.parts:
            raise RuntimeError(f"Unexpected runtime artifact in the delivery: {path}")
    for path in files:
        if path.suffix == ".py":
            compile(path.read_text(encoding="utf-8"), str(path), "exec")
    def record(path: Path) -> dict:
        return {"path": path.relative_to(PACKAGE).as_posix(), "bytes": path.stat().st_size, "sha256": sha256(path)}
    with ThreadPoolExecutor(max_workers=4) as pool:
        records = list(pool.map(record, files))
    index = PACKAGE / "PACKAGE_FILES.jsonl"
    index.write_text("".join(json.dumps(item, ensure_ascii=False) + "\n" for item in records), encoding="utf-8")
    files.append(index)
    print(f"Creating delivery ZIP: {len(files)} files", flush=True)
    with zipfile.ZipFile(ZIP, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6) as archive:
        for path in files:
            archive.write(path, arcname=f"{PACKAGE.name}/{path.relative_to(PACKAGE).as_posix()}")
    print("Checking every ZIP entry against the delivery folder...", flush=True)
    with zipfile.ZipFile(ZIP, "r") as archive:
        if len(archive.infolist()) != len(files):
            raise RuntimeError("ZIP file count differs")
        for path in files:
            name = f"{PACKAGE.name}/{path.relative_to(PACKAGE).as_posix()}"
            result = hashlib.sha256()
            with archive.open(name) as handle:
                for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                    result.update(chunk)
            if result.hexdigest() != sha256(path):
                raise RuntimeError(f"ZIP content differs: {name}")
    report = {
        "status": "pass",
        "package": str(PACKAGE),
        "package_file_count": len(files),
        "package_bytes": sum(path.stat().st_size for path in files),
        "zip": str(ZIP),
        "zip_bytes": ZIP.stat().st_size,
        "zip_sha256": sha256(ZIP),
        "all_zip_entries_equal_to_delivery_files": True,
        "original_generator_unchanged": sha256(PACKAGE / "original/prepare_r61_universal_dataset.py") == json.loads((PACKAGE / "recipe.json").read_text(encoding="utf-8"))["original_generator_sha256"],
        "originals_preserved": True,
    }
    (VALIDATION / "delivery_check.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, indent=2), flush=True)


if __name__ == "__main__":
    main()
