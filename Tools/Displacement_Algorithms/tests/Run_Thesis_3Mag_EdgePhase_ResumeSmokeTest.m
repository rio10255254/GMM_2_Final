function Run_Thesis_3Mag_EdgePhase_ResumeSmokeTest()
% Verifies a stopped thesis run can resume without rerunning completed cases.

scriptDir = fileparts(mfilename('fullpath'));
toolDir = fileparts(scriptDir);
outputRoot = fullfile(toolDir, 'tests', 'thesis_3mag_edge_phase_resume_smoketest');
if exist(outputRoot, 'dir') == 7
    rmdir(outputRoot, 's');
end

Run_Thesis_3Mag_EdgePhase_SelectROI( ...
    'outputRoot', outputRoot, ...
    'autoRoi', [560, 80, 320, 320], ...
    'maxCases', 4, ...
    'showFigures', false);

Run_Thesis_3Mag_EdgePhase_SelectROI( ...
    'outputRoot', outputRoot, ...
    'autoRoi', [560, 80, 320, 320], ...
    'maxCases', 5, ...
    'showFigures', false, ...
    'resumeExisting', true);

summaryPath = fullfile(outputRoot, 'final_tables', 'edge_phase_summary.csv');
summaryTable = readtable(summaryPath, 'VariableNamingRule', 'preserve');
assert(height(summaryTable) == 5, 'Resume run should contain the four old cases plus one new case.');
assert(any(summaryTable.case == "20x_1um_raw"), 'Resume run did not continue into the fifth case.');
end
