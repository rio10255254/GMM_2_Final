"""Rebuild the two fixed R108 synthetic inputs without importing any trainer.

Uses only named original generation functions from hash-locked sources. Writes
to a new external folder; never loads a model, imports torch, or runs inference.
"""
from __future__ import annotations
import argparse
import ast
import hashlib
import json
import math
from pathlib import Path
import sys

import cv2
import numpy as np

SOURCES = {
    'B': ('Experiments/R108B_StagedParallelOpticalExpertsMicroprobe/scripts/run_microprobe.py',
          'c70d8cb39f65ebf06428f3dd28f20f4e3a3de1368c95e4556c044dad3e3c89c1',
          ['sha256', 'polygon_points', 'draw_mask', 'low_field', 'render_scene', 'generate_split', 'prepare_data'],
          ['SIZE', 'SUPER', 'ROLES', 'TRAIN_FAMILIES', 'HOLDOUT_FAMILIES']),
    'E': ('Experiments/R108E_ContourConservingProfileRendererMicroprobe/scripts/run_probe.py',
          '2bfe9ee12f1450aa732b165b5c91a0c5b6c93a31a65e357ca140bfa99cbe5527',
          ['sha256', 'low_field', 'motion_kernel', 'angular_wedge', 'render', 'build_data'],
          ['BASE_SHA', 'CHALLENGES']),
}
EXPECTED = {'B': 'e01a97bc2b361195d550a6f3c5262e354b2424f8676ae9045c6abed765d39185',
            'E': '3e3ed993a03a0b354888b3d28edc4d2edcc26ee624f317e4615bfcb5a41b7663'}


def selected_generator(root: Path, key: str) -> dict:
    relative, expected, functions, constants = SOURCES[key]
    path = root / relative
    body = path.read_bytes()
    if hashlib.sha256(body).hexdigest() != expected:
        raise ValueError('Original generation source changed: ' + relative)
    tree = ast.parse(body.decode('utf-8-sig'))
    selected = [n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name in functions]
    if {n.name for n in selected} != set(functions):
        raise ValueError('Missing original generation function')
    namespace = dict(np=np, cv2=cv2, math=math, hashlib=hashlib, json=json, Path=Path)
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            if name in constants:
                namespace[name] = ast.literal_eval(node.value)
    if not all(name in namespace for name in constants):
        raise ValueError('Missing generation constants')
    module = ast.Module(body=[ast.ImportFrom(module='__future__', names=[ast.alias(name='annotations')], level=0), *selected], type_ignores=[])
    exec(compile(ast.fix_missing_locations(module), str(path), 'exec'), namespace)
    return namespace


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    root, output = args.root.resolve(), args.output.resolve()
    if output.exists() or output.is_relative_to(root):
        raise FileExistsError('Use a new output folder outside the source repository')
    b, e = selected_generator(root, 'B'), selected_generator(root, 'E')
    output.mkdir(parents=True)
    bdir = output / 'R108B'; edir = output / 'R108E'
    bdir.mkdir(); edir.mkdir()
    b['DATA_DIR'] = bdir
    b['prepare_data']()
    bpath = bdir / 'microprobe_data.npz'
    if hashlib.sha256(bpath.read_bytes()).hexdigest() != EXPECTED['B']:
        raise ValueError('R108B regenerated bytes differ; outputs retained for inspection')
    e.update(DATA=edir, BASE=bpath)
    e['build_data']()
    epath = edir / 'profile_renderer_data.npz'
    if hashlib.sha256(epath.read_bytes()).hexdigest() != EXPECTED['E']:
        raise ValueError('R108E regenerated bytes differ; outputs retained for inspection')
    assert 'torch' not in sys.modules
    result = {'status': 'PASS', 'original_sources': {k: {'path': v[0], 'sha256': v[1]} for k,v in SOURCES.items()},
              'generated_files': [{'path': p.relative_to(output).as_posix(), 'sha256': hashlib.sha256(p.read_bytes()).hexdigest(), 'bytes': p.stat().st_size} for p in (bpath, epath)],
              'historical_source_hashes_matched': True, 'numpy_version': np.__version__, 'opencv_version': cv2.__version__,
              'torch_imported': False, 'model_training_or_inference_executed': False}
    (output/'GENERATION_VERIFIED.json').write_text(json.dumps(result, indent=2), encoding='utf-8')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
