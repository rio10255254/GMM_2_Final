"""
GeoEdge R26 Performance Benchmark - Device Setup
=================================================
Interactive script to set up a new device for running benchmarks.

Run this ONCE on a new machine after git clone:

    python AnalysisLab/r26/performance/scripts/setup_device.py

It will:
  1. Ask where the model assets are (USB drive, cloud folder, etc.)
  2. Ask for a device name
  3. Detect GPU info
  4. Generate configs/device_config.py
  5. Validate that everything works
"""
from __future__ import annotations

import platform
import shutil
import sys
from pathlib import Path

# ---------------------------------------------------------------------------
SCRIPT_DIR = Path(__file__).resolve().parent
PERF_ROOT = SCRIPT_DIR.parent
CONFIG_PATH = PERF_ROOT / "configs" / "device_config.py"
MODEL_DIR = PERF_ROOT.parents[2] / "Model"
DEFAULT_TEST_INPUT = PERF_ROOT.parent / "single_image" / "inputs"

REQUIRED_FILES = {
    "best_tradeoff.pth.tar": "R26 model checkpoint",
    "PSF_fitted_2D_FOVstack.mat": "PSF fitted file",
}
OPTIONAL_DIRS = {
    "tra_src_ring": "Training input images (for training benchmark)",
    "tra_lbl_ring": "Training label images (for training benchmark)",
}

SEPARATOR = "=" * 60


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def ask(prompt: str, default: str | None = None) -> str:
    if default:
        prompt = f"{prompt} [{default}]: "
    else:
        prompt = f"{prompt}: "
    val = input(prompt).strip()
    return val if val else (default or "")


def check_torch() -> dict | None:
    try:
        import torch
        info = {
            "torch_version": torch.__version__,
            "cuda_available": torch.cuda.is_available(),
        }
        if torch.cuda.is_available():
            info["gpu_name"] = torch.cuda.get_device_name(0)
            info["gpu_count"] = torch.cuda.device_count()
        return info
    except ImportError:
        return None


def find_assets(source_dir: Path) -> dict:
    """Check which required/optional assets exist in source_dir."""
    found = {}
    # Required files - search recursively
    for filename, desc in REQUIRED_FILES.items():
        direct = source_dir / filename
        if direct.exists():
            found[filename] = direct
        else:
            matches = list(source_dir.rglob(filename))
            if matches:
                found[filename] = matches[0]

    # Optional directories
    for dirname, desc in OPTIONAL_DIRS.items():
        direct = source_dir / dirname
        if direct.is_dir():
            found[dirname] = direct
        else:
            matches = [d for d in source_dir.rglob(dirname) if d.is_dir()]
            if matches:
                found[dirname] = matches[0]

    return found


def generate_config(device_name: str, checkpoint: Path, psf: Path,
                    test_input: Path, src_dir: Path | None,
                    lbl_dir: Path | None, cuda_device: int | None) -> str:
    """Generate device_config.py content."""
    def path_str(p: Path | None) -> str:
        if p is None:
            return "None"
        return f'Path(r"{p}")'

    return f'''"""
Device configuration for R26 performance benchmark.
====================================================
Auto-generated by setup_device.py on this machine.
Edit paths below if you move files around.
"""
from __future__ import annotations

from pathlib import Path

# ---------------------------------------------------------------------------
# Device identity
# ---------------------------------------------------------------------------
DEVICE_NAME: str = "{device_name}"

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
CHECKPOINT: Path = {path_str(checkpoint)}
PSF_PATH: Path = {path_str(psf)}
TEST_INPUT_DIR: Path = {path_str(test_input)}
TRAINING_SRC_DIR: Path | None = {path_str(src_dir)}
TRAINING_LBL_DIR: Path | None = {path_str(lbl_dir)}

# ---------------------------------------------------------------------------
# Hardware selection
# ---------------------------------------------------------------------------
CUDA_DEVICE: int | None = {cuda_device if cuda_device is not None else "None"}
INCLUDE_CPU: bool = False

# ---------------------------------------------------------------------------
# Training benchmark settings
# ---------------------------------------------------------------------------
TRAINING_MODE: str = "quick"
TRAINING_QUICK_EPOCHS: int = 3
TRAINING_FULL_EPOCHS: int | None = None

# ---------------------------------------------------------------------------
# Inference benchmark settings
# ---------------------------------------------------------------------------
WARMUP_RUNS: int = 5
BENCHMARK_RUNS: int = 50
BATCH_SIZES: list[int] = [1]
'''


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    print(SEPARATOR)
    print("  GeoEdge R26 Performance Benchmark - Device Setup")
    print(SEPARATOR)
    print()

    # --- Step 1: Check Python environment ---
    print("[1/5] Checking Python environment...")
    torch_info = check_torch()
    if torch_info is None:
        print("  ERROR: PyTorch not installed.")
        print("  Please install PyTorch first:")
        print("    pip install torch torchvision")
        print("  See https://pytorch.org/get-started/locally/ for CUDA-specific versions.")
        sys.exit(1)
    print(f"  PyTorch {torch_info['torch_version']}")
    if torch_info["cuda_available"]:
        print(f"  GPU: {torch_info['gpu_name']} (x{torch_info['gpu_count']})")
    else:
        print("  GPU: None (will run on CPU only)")
    print()

    # --- Step 2: Check Model/ code ---
    print("[2/5] Checking model code...")
    if not MODEL_DIR.is_dir():
        print(f"  ERROR: Model/ directory not found at {MODEL_DIR}")
        print("  Make sure you cloned the full repo.")
        sys.exit(1)
    key_files = [
        "GeoEdgeAlignSR_v1_ModelA_v5_NoCoord.py",
        "GeoEdgeAlignSR_v1_Infer_v5_NoCoord_return_v2_SimpleTest.py",
        "GeoEdgeAlignSR_v1_Utils.py",
    ]
    missing_code = [f for f in key_files if not (MODEL_DIR / f).exists()]
    if missing_code:
        print(f"  ERROR: Missing model files: {missing_code}")
        sys.exit(1)
    print(f"  Model code OK ({MODEL_DIR})")
    print()

    # --- Step 3: Locate assets ---
    print("[3/5] Locating model assets...")
    print("  The benchmark needs these files (not included in git):")
    print()
    for f, desc in REQUIRED_FILES.items():
        print(f"    [required] {f}  ({desc})")
    for d, desc in OPTIONAL_DIRS.items():
        print(f"    [optional] {d}/  ({desc})")
    print()
    print("  These should be on a USB drive, cloud folder, or local path.")

    source_path_str = ask("  Enter the path to the folder containing these files")
    if not source_path_str:
        print("  ERROR: No path provided.")
        sys.exit(1)
    source_dir = Path(source_path_str).resolve()
    if not source_dir.is_dir():
        print(f"  ERROR: Not a directory: {source_dir}")
        sys.exit(1)

    found = find_assets(source_dir)
    print()
    print("  Found:")
    for name in list(REQUIRED_FILES) + list(OPTIONAL_DIRS):
        if name in found:
            print(f"    OK  {name}  ->  {found[name]}")
        elif name in REQUIRED_FILES:
            print(f"    MISSING  {name}  (REQUIRED)")
        else:
            print(f"    --  {name}  (optional, will use synthetic data)")

    missing_required = [f for f in REQUIRED_FILES if f not in found]
    if missing_required:
        print(f"\n  ERROR: Missing required files: {missing_required}")
        print(f"  Make sure they are somewhere inside: {source_dir}")
        sys.exit(1)
    print()

    # --- Step 4: Device name ---
    print("[4/5] Device configuration...")
    default_name = ""
    if torch_info["cuda_available"]:
        gpu = torch_info["gpu_name"].replace("NVIDIA ", "").replace(" ", "_")
        hostname = platform.node().replace(" ", "_")[:20]
        default_name = f"{gpu}_{hostname}"
    else:
        hostname = platform.node().replace(" ", "_")[:20]
        default_name = f"CPU_{hostname}"

    device_name = ask("  Device name (unique identifier)", default_name)
    if not device_name:
        device_name = default_name

    cuda_device = None
    if torch_info["cuda_available"]:
        if torch_info["gpu_count"] > 1:
            cuda_str = ask(f"  Which GPU to use? (0-{torch_info['gpu_count']-1})", "0")
            cuda_device = int(cuda_str)
        else:
            cuda_device = 0
    print()

    # --- Step 5: Generate config ---
    print("[5/5] Generating configuration...")

    checkpoint_path = found["best_tradeoff.pth.tar"].resolve()
    psf_path = found["PSF_fitted_2D_FOVstack.mat"].resolve()
    test_input = DEFAULT_TEST_INPUT.resolve()
    src_dir = found.get("tra_src_ring")
    lbl_dir = found.get("tra_lbl_ring")
    if src_dir:
        src_dir = src_dir.resolve()
    if lbl_dir:
        lbl_dir = lbl_dir.resolve()

    config_content = generate_config(
        device_name=device_name,
        checkpoint=checkpoint_path,
        psf=psf_path,
        test_input=test_input,
        src_dir=src_dir,
        lbl_dir=lbl_dir,
        cuda_device=cuda_device,
    )

    CONFIG_PATH.write_text(config_content, encoding="utf-8")
    print(f"  Config written to: {CONFIG_PATH}")
    print()

    # --- Summary ---
    print(SEPARATOR)
    print("  Setup Complete!")
    print(SEPARATOR)
    print()
    print(f"  Device name:    {device_name}")
    print(f"  Checkpoint:     {checkpoint_path}")
    print(f"  PSF:            {psf_path}")
    print(f"  Test input:     {test_input}")
    if src_dir and lbl_dir:
        print(f"  Training src:   {src_dir}")
        print(f"  Training lbl:   {lbl_dir}")
        print(f"  Training data:  real data")
    else:
        print(f"  Training data:  synthetic (training data not found)")
    print()
    print("  Now run:")
    print()
    print("    # Inference benchmark")
    print("    python AnalysisLab/r26/performance/scripts/run_inference_benchmark.py")
    print()
    print("    # Training benchmark")
    print("    python AnalysisLab/r26/performance/scripts/run_training_benchmark.py")
    print()
    print("    # After running on multiple devices, compare:")
    print("    python AnalysisLab/r26/performance/scripts/run_cross_device_compare.py")
    print()


if __name__ == "__main__":
    main()
