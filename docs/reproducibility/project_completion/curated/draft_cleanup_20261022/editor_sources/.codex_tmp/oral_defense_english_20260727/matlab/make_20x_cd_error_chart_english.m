function make_20x_cd_error_chart_english(outputPath)
% Recreate the slide-41 20x CD error chart with English-only labeling.

if nargin < 1 || strlength(string(outputPath)) == 0
    outputPath = fullfile(fileparts(fileparts(mfilename('fullpath'))), ...
        'assets_english', 'custom', '20x_cd_median_absolute_error_english.png');
end

values = [192.1, 161.2, 117.0];
labels = {'Raw', 'Wiener', 'MOSR'};
colors = [0.6902, 0.2784, 0.0745; ...
          0.8078, 0.4980, 0.0000; ...
          0.0784, 0.3882, 0.6431];

outDir = fileparts(outputPath);
if ~isfolder(outDir)
    mkdir(outDir);
end

fig = figure('Visible', 'off', 'Color', 'white', ...
    'Units', 'pixels', 'Position', [100, 100, 1894, 1358]);
ax = axes(fig, 'Position', [0.068, 0.085, 0.922, 0.865]);
b = bar(ax, 1:3, values, 0.60, 'FaceColor', 'flat', 'EdgeColor', 'none');
b.CData = colors;

set(ax, ...
    'XLim', [0.2, 3.8], ...
    'YLim', [0, 250], ...
    'XTick', 1:3, ...
    'XTickLabel', labels, ...
    'YTick', 0:50:200, ...
    'FontName', 'Arial', ...
    'FontSize', 26, ...
    'LineWidth', 2.4, ...
    'TickDir', 'in', ...
    'TickLength', [0.012, 0.012], ...
    'Box', 'off', ...
    'XGrid', 'off', ...
    'YGrid', 'on', ...
    'GridColor', [0.84, 0.84, 0.84], ...
    'GridAlpha', 1, ...
    'Layer', 'top');

ylabel(ax, 'Median Absolute CD Error (nm)', ...
    'FontName', 'Arial', 'FontSize', 29, 'FontWeight', 'normal');

set(fig, 'PaperPositionMode', 'auto');
print(fig, outputPath, '-dpng', '-r100');
close(fig);

fprintf('Created %s with values Raw=%.1f, Wiener=%.1f, MOSR=%.1f nm.\n', ...
    outputPath, values(1), values(2), values(3));
end
